pub fn emoji_query_matches(query: &str, category: &str, glyph: &str, keywords: &str) -> bool {
    let q = query.trim().to_lowercase();
    if q.is_empty() {
        return true;
    }
    if glyph.contains(query.trim()) {
        return true;
    }
    let hay = format!("{category} {keywords}").to_lowercase();
    if hay.contains(&q) {
        return true;
    }
    // Subsequence fuzzy: "snr" ~ "signal radio", "cof" ~ "coffee"
    let mut need = q.chars();
    let Some(mut n) = need.next() else {
        return true;
    };
    for ch in hay.chars() {
        if ch == n {
            match need.next() {
                Some(next) => n = next,
                None => return true,
            }
        }
    }
    false
}
